"""EU AI Act Art. 50 AI transparency, citation grounding, and Model Armor provenance (Pillar 4: Compliance & Governance).

Evaluates final agent responses against retrieved document chunks, counts inline `[source, p.X]`
citations, and packages machine-readable provenance metadata (`ComplianceMetadata`) for JSON
(`POST /agent`) and SSE (`POST /agent/stream`) responses.
"""

import re
from typing import Any, Dict, List, Optional, Sequence

from pydantic import BaseModel, Field

from src.core.ai_security.guardrails import validate_llm_model
from src.core.compliance.residency import validate_gcp_region
from src.core.compliance.state import (
    GUARDRAIL_FILTER_LABELS,
    get_guardrail_actions,
    get_retrieved_chunks_count,
    was_model_armor_active,
    was_pii_filtered,
)
from src.core.context import get_request_id

MODEL_ARMOR_DEFAULT_FILTERS: List[str] = [
    "pi_and_jailbreak",
    "malicious_uri",
    "rai",
    "sdp",
]

_CITATION_BRACKET_RE = re.compile(
    r"\[[^\[\]\n]+?,\s*(?:pp?\.?|pages?)\s*\d+[^\[\]\n]*\]"
    r"|\([^\(\)\n]+?\.(?:pdf|docx?|txt|md|csv|html?)\s*,\s*(?:pp?\.?|pages?)\s*\d+[^\(\)\n]*\)",
    re.IGNORECASE,
)
_PAGE_REF_RE = re.compile(r"(?:pp?\.?|pages?)\s*\d+", re.IGNORECASE)


def count_inline_citations(answer: Optional[str]) -> int:
    """Counts inline `[source, p.X]` / `(source.pdf, p.X)` document page citations in an answer.

    Args:
        answer: Final assistant response text to inspect.

    Returns:
        Total number of inline page references detected across citation brackets.
    """
    if not answer or not isinstance(answer, str):
        return 0
    total = 0
    for match in _CITATION_BRACKET_RE.findall(answer):
        refs = _PAGE_REF_RE.findall(match)
        total += max(len(refs), 1)
    return total


def has_thread_retrieved_chunks(
    messages: Optional[Sequence[Dict[str, Any]]] = None,
    scoped_thread_id: Optional[str] = None,
    checkpointer: Any = None,
) -> bool:
    """Checks whether XML-spotlighted `<retrieved_chunk>` chunks exist in the turn or thread memory.

    Args:
        messages: Optional sequence of serialized message dicts emitted during the current turn.
        scoped_thread_id: Optional `{uid}:{thread_id}` LangGraph checkpoint key for multi-turn follow-ups.
        checkpointer: Optional LangGraph checkpointer (`InMemorySaver`) holding thread history.

    Returns:
        True if at least one `<retrieved_chunk ...>` block is present in the turn or prior thread state.
    """
    if messages:
        for msg in messages:
            if isinstance(msg, dict) and "<retrieved_chunk " in str(msg.get("content") or ""):
                return True

    if scoped_thread_id and checkpointer is not None:
        try:
            tup = checkpointer.get_tuple({"configurable": {"thread_id": scoped_thread_id}})
            if tup and tup.checkpoint:
                channel_msgs = (tup.checkpoint.get("channel_values") or {}).get("messages") or []
                for msg in channel_msgs:
                    content = getattr(msg, "content", "")
                    if "<retrieved_chunk " in str(content or ""):
                        return True
        except Exception:
            pass

    return False


class GuardrailAction(BaseModel):
    """Structured record of a Cloud Model Armor or Gemini safety action triggered during the turn."""

    filter: str = Field(
        ...,
        description="Filter identifier (pi_and_jailbreak, malicious_uri, rai, sdp, gemini_safety)",
    )
    label: str = Field(..., description="Human-readable filter name")
    action: str = Field(
        ...,
        description="Action taken by the guardrail ('blocked' or 'redacted')",
    )
    stage: str = Field(
        ...,
        description="Pipeline stage ('input', 'retrieval', 'model', or 'output')",
    )
    details: List[str] = Field(
        default_factory=list,
        description="Optional matched subcategories (e.g. HARASSMENT, DANGEROUS for RAI)",
    )


class ComplianceMetadata(BaseModel):
    """EU AI Act Art. 50 AI transparency, grounding & Model Armor provenance metadata."""

    ai_generated: bool = Field(
        default=True,
        description="True when generated by the LLM; False when replaced by a deterministic safety/security refusal",
    )
    model: str = Field(..., description="Approved regional Vertex AI LLM model identifier")
    region: str = Field(
        ...,
        description="Pinned single GCP region where inference and retrieval executed",
    )
    grounding_enforced: bool = Field(
        default=True,
        description="Indicates system-level grounding and citation guardrails were enforced",
    )
    grounded: bool = Field(
        default=False,
        description="True when the answer cites retrieved document chunks and was not blocked by guardrails",
    )
    citation_count: int = Field(
        default=0,
        description="Number of inline document page citations present in the final answer",
    )
    retrieved_chunks: int = Field(
        default=0,
        description="Number of vectorstore chunks retrieved during this turn",
    )
    pii_filtered: bool = Field(
        default=False,
        description="True when Sensitive Data Protection / Model Armor redacted PII during the request",
    )
    model_armor_active: bool = Field(
        default=False,
        description="True when Google Cloud Model Armor actively screened this turn",
    )
    filters_checked: List[str] = Field(
        default_factory=list,
        description="Cloud Model Armor filter suites evaluated on this turn",
    )
    guardrail_actions: List[GuardrailAction] = Field(
        default_factory=list,
        description="All Cloud Model Armor and Gemini safety actions (blocks or redactions) triggered on this turn",
    )
    request_id: str = Field(..., description="End-to-end audit correlation identifier")


def build_compliance_metadata(
    model_name: Optional[str] = None,
    answer: Optional[str] = None,
    messages: Optional[Sequence[Dict[str, Any]]] = None,
    scoped_thread_id: Optional[str] = None,
    checkpointer: Any = None,
) -> ComplianceMetadata:
    """Constructs EU AI Act Art. 50 provenance, grounding, and Model Armor metadata for the active turn.

    Args:
        model_name: Requested or default generative LLM model identifier.
        answer: Final assistant response string emitted to the user.
        messages: Optional sequence of message event dictionaries from the turn.
        scoped_thread_id: Optional `{uid}:{thread_id}` key used to verify multi-turn retrieval context.
        checkpointer: Optional LangGraph checkpointer (`InMemorySaver`) for multi-turn lookup.

    Returns:
        Populated `ComplianceMetadata` instance ready for JSON serialization or SSE emission.
    """
    raw_actions = get_guardrail_actions()
    was_blocked = any(item.get("action") == "blocked" for item in raw_actions)
    retrieved_chunks = get_retrieved_chunks_count()
    citation_count = 0 if was_blocked else count_inline_citations(answer)
    has_evidence = (retrieved_chunks > 0) or has_thread_retrieved_chunks(
        messages=messages,
        scoped_thread_id=scoped_thread_id,
        checkpointer=checkpointer,
    )
    grounded = (not was_blocked) and (citation_count > 0) and has_evidence
    armor_active = was_model_armor_active()

    return ComplianceMetadata(
        ai_generated=not was_blocked,
        model=validate_llm_model(model_name),
        region=validate_gcp_region(),
        grounding_enforced=True,
        grounded=grounded,
        citation_count=citation_count,
        retrieved_chunks=retrieved_chunks,
        pii_filtered=was_pii_filtered(),
        model_armor_active=armor_active,
        filters_checked=list(MODEL_ARMOR_DEFAULT_FILTERS) if armor_active else [],
        guardrail_actions=[GuardrailAction(**item) for item in raw_actions],
        request_id=get_request_id(),
    )


